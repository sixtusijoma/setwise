// Generates the library seed migration from data/exercise-library.json (the single source of
// truth, also bundled by the app for local mode). Upserts by slug, so re-running is safe.
import { readFileSync, writeFileSync } from 'node:fs';

const library = JSON.parse(readFileSync(new URL('../data/exercise-library.json', import.meta.url)));
const q = (s) => `'${s.replaceAll("'", "''")}'`;

const rows = library.map(
  (e) =>
    `  (null, ${q(e.slug)}, ${q(e.name)}, ${q(e.muscle_group)}, ${q(e.equipment)}, ` +
    `array[${(e.aliases ?? []).map(q).join(', ')}]::text[])`,
);

const sql = `-- Generated by scripts/gen-exercise-seed.mjs from data/exercise-library.json. Do not edit.
insert into public.exercises (owner_id, slug, name, muscle_group, equipment, aliases) values
${rows.join(',\n')}
on conflict (slug) do update set
  name = excluded.name,
  muscle_group = excluded.muscle_group,
  equipment = excluded.equipment,
  aliases = excluded.aliases;
`;

// Pass a new migration name once the previous seed is applied remotely, e.g. `20261009000000_exercise_library.sql`.
const file = process.argv[2] ?? '20261008000100_exercise_library.sql';
writeFileSync(new URL(`../supabase/migrations/${file}`, import.meta.url), sql);
console.log(`${library.length} exercises`);
